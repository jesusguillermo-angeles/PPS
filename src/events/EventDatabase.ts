export type EventKind = 'Elite Guard' | 'Gambit' | 'Shards' | 'Coliseum' | 'Faction Wars' | 'Automata';
export type EventRecord = {
  id: string;
  name: string;
  kind: EventKind;
  year: number;
  edition?: string;
  reissue?: boolean;
  image: string;
  source: 'archive-pdf' | 'wiki-history';
};

const eg = (id:number,name:string,year:number,bis=false): EventRecord => ({id:`eg-${id}${bis?'-bis':''}`,name:`Elite Guard ${id}${bis?' (bis)':''}${name?` - ${name}`:''}`,kind:'Elite Guard',year,edition:bis?'Reissued':undefined,reissue:bis,image:'/historical/elite-guard.jpg',source:'archive-pdf'});
const gambit = (id:number,year:number,bis=false,name=''): EventRecord => ({id:`gambit-${id}${bis?'-bis':''}`,name:`Gambit ${id}${bis?' (bis)':''}${name?` - ${name}`:''}`,kind:'Gambit',year,image:'/historical/elite-guard.jpg',source:'archive-pdf'});
const shards = (id:number,year:number,edition='Crystalis edition'): EventRecord => ({id:`shards-${id}`,name:`Shards ${id} - (${edition})`,kind:'Shards',year,image:'/historical/shards.jpg',source:'archive-pdf'});
const col = (id:number,year:number,name=''): EventRecord => ({id:`col-${id}`,name:`Coliseum ${id}${name?` - ${name}`:''}`,kind:'Coliseum',year,image:'/historical/coliseum.jpg',source:'wiki-history'});
const faction = (id:number,year:number,name:string): EventRecord => ({id:`faction-${id}`,name:`Faction Wars ${id} - ${name}`,kind:'Faction Wars',year,image:'/historical/elite-guard.jpg',source:'archive-pdf'});

